create table if not exists public.concept_posts (
  id bigint generated by default as identity primary key,
  subject text not null,
  title text not null,
  slug text not null unique,
  excerpt text,
  body text,
  published boolean not null default false,
  published_at timestamptz,
  created_at timestamptz not null default now(),
  constraint concept_posts_published_at_required
    check (not published or published_at is not null)
);

alter table public.concept_posts enable row level security;

drop policy if exists "Anyone can read published concept posts"
  on public.concept_posts;
create policy "Anyone can read published concept posts"
  on public.concept_posts
  for select
  to anon, authenticated
  using (published);

grant select on public.concept_posts to anon, authenticated;

create table if not exists public.exam_attempts (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users (id) on delete cascade,
  subject text,
  total_questions integer not null check (total_questions >= 0),
  questions_answered integer not null check (questions_answered >= 0),
  correct_answers integer not null check (correct_answers >= 0),
  score numeric(5, 2),
  started_at timestamptz not null,
  completed_at timestamptz,
  time_limit_seconds integer check (
    time_limit_seconds is null or time_limit_seconds >= 0
  ),
  created_at timestamptz not null default now(),
  constraint exam_attempts_counts_valid check (
    questions_answered <= total_questions
    and correct_answers <= questions_answered
  ),
  constraint exam_attempts_score_valid check (
    score is null or (score >= 0 and score <= 100)
  )
);

create index if not exists exam_attempts_user_completed_idx
  on public.exam_attempts (user_id, completed_at desc)
  where completed_at is not null;

alter table public.exam_attempts enable row level security;

drop policy if exists "Users can read their own exam attempts"
  on public.exam_attempts;
create policy "Users can read their own exam attempts"
  on public.exam_attempts
  for select
  to authenticated
  using ((select auth.uid()) = user_id);

drop policy if exists "Users can create their own exam attempts"
  on public.exam_attempts;
create policy "Users can create their own exam attempts"
  on public.exam_attempts
  for insert
  to authenticated
  with check ((select auth.uid()) = user_id);

grant select, insert on public.exam_attempts to authenticated;

create table if not exists public.user_streaks (
  user_id uuid primary key references auth.users (id) on delete cascade,
  current_streak integer not null default 0 check (current_streak >= 0),
  longest_streak integer not null default 0 check (longest_streak >= 0),
  last_activity_date date,
  updated_at timestamptz not null default now(),
  constraint user_streaks_longest_gte_current
    check (longest_streak >= current_streak)
);

alter table public.user_streaks enable row level security;

drop policy if exists "Users can read their own streak"
  on public.user_streaks;
create policy "Users can read their own streak"
  on public.user_streaks
  for select
  to authenticated
  using ((select auth.uid()) = user_id);

drop policy if exists "Users can update their own streak"
  on public.user_streaks;
create policy "Users can update their own streak"
  on public.user_streaks
  for all
  to authenticated
  using ((select auth.uid()) = user_id)
  with check ((select auth.uid()) = user_id);

grant select, insert, update on public.user_streaks to authenticated;

create or replace function public.get_my_streak()
returns table (
  current_streak integer,
  longest_streak integer,
  last_activity_date date
)
language sql
stable
security invoker
set search_path = ''
as $$
  select
    case
      when s.last_activity_date >= (now() at time zone 'Africa/Lagos')::date - 1
        then s.current_streak
      else 0
    end,
    s.longest_streak,
    s.last_activity_date
  from public.user_streaks as s
  where s.user_id = (select auth.uid());
$$;

revoke all on function public.get_my_streak() from public, anon;
grant execute on function public.get_my_streak() to authenticated;

create or replace function public.bump_streak()
returns table (
  current_streak integer,
  longest_streak integer,
  last_activity_date date
)
language plpgsql
security invoker
set search_path = ''
as $$
declare
  today date := (now() at time zone 'Africa/Lagos')::date;
begin
  if (select auth.uid()) is null then
    raise exception 'Authentication is required to update a streak.';
  end if;

  insert into public.user_streaks as existing (
    user_id,
    current_streak,
    longest_streak,
    last_activity_date,
    updated_at
  )
  values ((select auth.uid()), 1, 1, today, now())
  on conflict (user_id) do update
  set
    current_streak = case
      when existing.last_activity_date = today then existing.current_streak
      when existing.last_activity_date = today - 1 then existing.current_streak + 1
      else 1
    end,
    longest_streak = greatest(
      existing.longest_streak,
      case
        when existing.last_activity_date = today then existing.current_streak
        when existing.last_activity_date = today - 1 then existing.current_streak + 1
        else 1
      end
    ),
    last_activity_date = today,
    updated_at = now()
  returning
    user_streaks.current_streak,
    user_streaks.longest_streak,
    user_streaks.last_activity_date
  into current_streak, longest_streak, last_activity_date;

  return next;
end;
$$;

revoke all on function public.bump_streak() from public, anon;
grant execute on function public.bump_streak() to authenticated;

notify pgrst, 'reload schema';
