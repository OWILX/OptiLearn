create table if not exists public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  full_name text,
  avatar_url text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  department text,
  premium boolean not null default false,
  premium_since timestamptz,
  premium_expires_at timestamptz
);

alter table public.profiles enable row level security;

drop policy if exists "Users can read their own profile"
  on public.profiles;
create policy "Users can read their own profile"
  on public.profiles
  for select
  to authenticated
  using ((select auth.uid()) = id);

drop policy if exists "Users can create their own profile"
  on public.profiles;
create policy "Users can create their own profile"
  on public.profiles
  for insert
  to authenticated
  with check ((select auth.uid()) = id);

drop policy if exists "Users can update their own profile"
  on public.profiles;
create policy "Users can update their own profile"
  on public.profiles
  for update
  to authenticated
  using ((select auth.uid()) = id)
  with check ((select auth.uid()) = id);

grant select, insert, update on public.profiles to authenticated;

create table if not exists public.study_progress (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users (id) on delete cascade,
  syllabus_id bigint not null references public.syllabus (id) on delete cascade,
  status text not null default 'not_started'
    check (status in ('not_started', 'in_progress', 'completed')),
  progress numeric not null default 0
    check (progress >= 0 and progress <= 100),
  started_at timestamptz,
  completed_at timestamptz,
  last_accessed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint study_progress_user_syllabus_unique unique (user_id, syllabus_id)
);

create index if not exists study_progress_user_status_idx
  on public.study_progress (user_id, status);

create index if not exists study_progress_user_last_accessed_idx
  on public.study_progress (user_id, last_accessed_at desc);

alter table public.study_progress enable row level security;

drop policy if exists "Users can access their own study progress"
  on public.study_progress;
create policy "Users can access their own study progress"
  on public.study_progress
  for all
  to authenticated
  using ((select auth.uid()) = user_id)
  with check ((select auth.uid()) = user_id);

grant select, insert, update, delete on public.study_progress to authenticated;
grant usage, select on sequence public.study_progress_id_seq to authenticated;

create or replace function public.avelune_plus_set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

drop trigger if exists profiles_set_updated_at on public.profiles;
create trigger profiles_set_updated_at
  before update on public.profiles
  for each row execute function public.avelune_plus_set_updated_at();

drop trigger if exists study_progress_set_updated_at on public.study_progress;
create trigger study_progress_set_updated_at
  before update on public.study_progress
  for each row execute function public.avelune_plus_set_updated_at();

revoke all on function public.avelune_plus_set_updated_at()
  from public, anon, authenticated;

notify pgrst, 'reload schema';
